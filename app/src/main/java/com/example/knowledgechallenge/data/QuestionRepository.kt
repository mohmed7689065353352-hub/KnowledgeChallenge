     * يعيد جولة من [size] سؤال. إذا كان [category] = null تُخلط الأسئلة من كل الأقسام (تحدٍّ سريع).
     */
    fun getRound(category: Category?, size: Int): List<Question> {
        val pool = if (category == null) allQuestions else allQuestions.filter { it.category == category }
        return pool.shuffled().take(size).map { it.withShuffledOptions() }
    }

    /** جولة اليوم: نفس الأسئلة ونفس الترتيب لكل المستخدمين في اليوم نفسه. */
    fun getDailyRound(epochDay: Long, size: Int): List<Question> {
        val random = Random(epochDay)
        return allQuestions.shuffled(random).take(size).map { it.withShuffledOptions(random) }
    }

